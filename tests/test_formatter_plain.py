# Case 6: flat => integrated
def test_format_plain_flat_overall() -> None:
    # Arrange:
    node = ast.literal_eval(_read_test_file(_get_test_data_path("expected_ir_flat.txt")))
    expected_output = _read_test_file(_get_test_data_path("expected_plain_flat.txt"))
    # Act
    actual_output = format_plain(node)
    print(actual_output)

    # Assert
    assert actual_output == expected_output


