""" Unit tests for the Plain Formatter Module (formatter_plain.py).

This module validates format_plain(), which takes an internal representation (IR) difference tree,
generated by build_diff() of the Builder Module (diff_builder.py), and generates a custom string, 'plain'.

Node formatting rules:
added	   Property '{path}' was added with value: {formatted_value}
removed	   Property '{path}' was removed
updated	   Property '{path}' was updated. From {old_formatted_value} to {new_formatted_value}
unchanged  Not shown

Value formatting rules:
Strings => wrapped in single quotes: 'blah blah' or '' if empty string
Numbers (int, float) => no quotes: 42, 3.14
Booleans => JSON notation: true, false
None => null
Composite values (dict or list) => the literal string [complex value]

The tests cover 12 cases - 6 for each type of IR, flat and nested. The tests cover the following possible situations:
1. empty dictionaries
2. unchanged status
3. added status
4. removed status
5. updated status
6. mixed (2. - 5.)
"""

import ast

from gendiff.formatters.formatter_plain import format_plain

from .helpers import _get_test_data_path, _read_test_file


# FLAT IRs
# Case 1: flat => empty node
def test_format_plain_flat_empty_node() -> None:
    # Arrange:
    node = []
    expected_output = ""

    # Act
    actual_output = format_plain(node)

    # Assert
    assert actual_output == expected_output


# Case 2: flat => status: unchanged
def test_format_plain_flat_status_unchanged() -> None:
    # Arrange:
    node = [{'key': 'host', 'status': 'unchanged', 'old_value': 'hexlet.io', 'new_value': 'hexlet.io', 'children': None}]
    expected_output = ""

    # Act
    actual_output = format_plain(node)

    # Assert
    assert actual_output == expected_output


# Case 3: flat => status: removed
def test_format_plain_flat_status_removed() -> None:
    # Arrange:
    node = [{'key': 'host', 'status': 'removed', 'old_value': 'hexlet.io', 'new_value': None, 'children': None}]
    expected_output = "Property 'host' was removed"

    # Act
    actual_output = format_plain(node)

    # Assert
    assert actual_output == expected_output


# Case 4: flat => status added
def test_format_plain_flat_status_added() -> None:
    # Arrange:
    node = [{'key': 'host', 'status': 'added', 'old_value': None, 'new_value': 'hexlet.io', 'children': None}]
