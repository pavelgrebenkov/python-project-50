# Case 5: flat => updated node
def test_format_plain_flat_status_updated() -> None:
    # Arrange:
    node = [{'key': 'host', 'status': 'updated', 'old_value': 'hexlet.io', 'new_value': 'hexlet.com', 'children': None}]
